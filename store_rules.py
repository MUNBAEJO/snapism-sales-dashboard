import re

# device_ingest.TEST_RE / device_ingest_snapism.TEST_RE 와 **같은 값이어야 한다.**
# 그쪽 두 파일은 이 값을 import 해서 쓴다.
TEST_RE = re.compile(r"테스트|test|샘플|sample|데모|demo|본사|오피스|창고|회의실|시험", re.I)

# SQL 쪽에서 쓰는 같은 패턴. DuckDB `regexp_matches(col, PATTERN, 'i')`.
TEST_PATTERN = "테스트|test|샘플|sample|데모|demo|본사|오피스|창고|회의실|시험"


def is_test(names) -> "pandas.Series":            # noqa: F821
    """pandas Series → 테스트 매장 여부(bool)."""
    return names.astype(str).str.contains(TEST_RE)


def not_test_sql(col: str = '"매장 이름"') -> str:
    """실매장만 남기는 WHERE 조각. 이름이 비어 있으면 **남긴다**(모르면 빼지 않는다)."""
    return (f"AND NOT regexp_matches(COALESCE(CAST({col} AS VARCHAR), ''), "
            f"'{TEST_PATTERN}', 'i')")
